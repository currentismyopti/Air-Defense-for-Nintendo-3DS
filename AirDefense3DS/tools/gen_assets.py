#!/usr/bin/env python3
"""Builds src/assets.c: bitmap font atlas and the aircraft photos.
Usage: gen_assets.py <photo_dir> <out_c>   (photos: a4.jpg f104.jpg a6.jpg fa18.jpg f111.jpg)"""
import sys, os
from PIL import Image, ImageDraw, ImageFont

FONT_DIR = "/usr/share/fonts/truetype/dejavu/"
FONTS = [("DejaVuSansCondensed-Bold.ttf", 9), ("DejaVuSans-Bold.ttf", 11), ("DejaVuSans-Bold.ttf", 20)]
AW, AH = 256, 256
CHARS = [chr(c) for c in range(32, 127)]

def build_fonts():
    atlas = Image.new("L", (AW, AH), 0)
    x = y = 1
    rowh = 0
    tables = []
    for fname, size in FONTS:
        font = ImageFont.truetype(FONT_DIR + fname, size)
        ascent, descent = font.getmetrics()
        glyphs = []
        for ch in CHARS:
            adv = int(round(font.getlength(ch)))
            bbox = font.getbbox(ch)
            w, h = max(0, bbox[2] - bbox[0]), max(0, bbox[3] - bbox[1])
            if ch == " " or w == 0 or h == 0:
                glyphs.append((0, 0, 0, 0, 0, 0, adv))
                continue
            if x + w + 1 > AW:
                x = 1
                y += rowh + 1
                rowh = 0
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-bbox[0], -bbox[1]), ch, font=font, fill=255)
            atlas.paste(im, (x, y))
            glyphs.append((x, y, w, h, bbox[0], bbox[1], adv))
            x += w + 1
            rowh = max(rowh, h)
        tables.append((size, ascent, descent, glyphs))
        x = 1
        y += rowh + 1
        rowh = 0
    assert y < AH - 4, y
    # solid white block for untextured-looking fills if ever needed
    for yy in range(AH - 4, AH):
        for xx in range(AW - 4, AW):
            atlas.putpixel((xx, yy), 255)
    return atlas, tables

def build_photos(d):
    sheet = Image.new("RGB", (256, 256), (0, 0, 0))
    names = ["a4", "f104", "a6", "fa18", "f111"]
    for i, n in enumerate(names):
        im = Image.open(os.path.join(d, n + ".jpg")).convert("RGB").resize((128, 72), Image.LANCZOS)
        sheet.paste(im, ((i % 2) * 128, (i // 2) * 72))
    return sheet

def carr(name, data, per=24):
    out = ["const unsigned char %s[%d] = {" % (name, len(data))]
    for i in range(0, len(data), per):
        out.append(",".join(str(b) for b in data[i:i + per]) + ",")
    out.append("};")
    return "\n".join(out)

def main():
    photo_dir, out = sys.argv[1], sys.argv[2]
    atlas, tables = build_fonts()
    photos = build_photos(photo_dir)
    atlas.save(os.path.join(os.path.dirname(out), "..", "tools", "font_preview.png"))
    src = ['/* Generated by tools/gen_assets.py. Do not edit. */', '#include "assets.h"', ""]
    src.append(carr("font_alpha", atlas.tobytes()))
    src.append(carr("photo_rgb", photos.tobytes()))
    for fi, (size, asc, desc, glyphs) in enumerate(tables):
        src.append("static const Glyph glyphs%d[95] = {" % fi)
        for g in glyphs:
            src.append("{%d,%d,%d,%d,%d,%d,%d}," % g)
        src.append("};")
    src.append("const Font fonts[3] = {")
    for fi, (size, asc, desc, glyphs) in enumerate(tables):
        src.append("{%d,%d,%d,glyphs%d}," % (size, asc, desc, fi))
    src.append("};")
    open(out, "w").write("\n".join(src) + "\n")

main()
